import { describe, expect, it } from 'vitest'
import type { editor } from 'monaco-editor'
import { afterClose } from '../src/renderer/src/documents'
import { gridLimits } from '../src/renderer/src/grid/constants'
import { documentFixture, deferred, TestEditor, type SaveResponse } from './fixtures/documents'

describe('query documents', () => {
  it('marks edits dirty and clears the marker when undo returns to saved content', () => {
    const { documents, model } = documentFixture()
    const tab = documents.create('query.sql', 'SELECT 1', 'master')
    const clean = documents.getSnapshot()
    expect(documents.get(tab.id)?.dirty).toBe(false)
    model(tab.id).edit('SELECT 2')
    const dirty = documents.getSnapshot()
    expect(dirty).not.toBe(clean)
    model(tab.id).edit('SELECT 3')
    expect(documents.getSnapshot()).toBe(dirty)
    expect('sql' in dirty.documents[0]).toBe(false)
    model(tab.id).undo(); model(tab.id).undo()
    expect(documents.get(tab.id)?.dirty).toBe(false)
    model(tab.id).redo()
    expect(documents.get(tab.id)?.dirty).toBe(true)
  })
  it('selects an adjacent tab and allows the last query to close', () => {
    const { documents } = documentFixture()
    const left = documents.create('left.sql', '', 'master', 'server-a')
    const right = documents.create('right.sql', '', 'analytics', 'server-b')
    const closed = afterClose([left, right], left.id, left.id)
    expect(closed.activeId).toBe(right.id)
    expect(closed.tabs[0].connectionId).toBe('server-b')
    expect(afterClose(closed.tabs, right.id, right.id)).toEqual({ tabs: [], activeId: '' })
  })
  it('owns models by URI and retains them and view state across switches and editor remounts', () => {
    const { documents, model, models } = documentFixture()
    const left = documents.create('left.sql', 'SELECT 1', 'master')
    const right = documents.create('right.sql', 'SELECT 2', 'master')
    const instance = new TestEditor(), binding = documents.bindEditor(instance.asEditor())
    documents.activate(left.id)
    const view = { cursorState: [], viewState: { scrollTop: 123 } } as unknown as editor.ICodeEditorViewState
    instance.viewState = view
    model(left.id).edit('SELECT 3')
    documents.activate(right.id); documents.activate(left.id)
    expect(instance.viewState).toBe(view)
    expect(instance.model).toBe(model(left.id))
    expect([...models.values()].some(value => value.disposed)).toBe(false)
    binding.dispose()
    const replacement = new TestEditor()
    documents.bindEditor(replacement.asEditor())
    expect(replacement.model).toBe(model(left.id))
    expect(replacement.viewState).toBe(view)
    model(left.id).undo()
    expect(model(left.id).getValue()).toBe('SELECT 1')
    documents.dispose()
    expect(replacement.model).toBeNull()
    expect([...models.values()].every(value => value.disposed)).toBe(true)
  })
  it('captures the saved revision while allowing later edits to remain dirty', async () => {
    const { documents, model, api } = documentFixture()
    const tab = documents.create('query.sql', '', 'master')
    model(tab.id).edit('SELECT 1')
    const pending = deferred<SaveResponse>()
    api.saveSqlFile.mockReturnValueOnce(pending.promise)
    const saving = documents.save(tab.id)
    expect(api.saveSqlFile).toHaveBeenCalledWith(expect.objectContaining({ content: 'SELECT 1' }))
    model(tab.id).edit('SELECT 2')
    pending.resolve({ ok: true, value: { id: 'file', name: 'saved.sql', path: 'C:/saved.sql', encoding: 'utf8', readOnly: false } })
    expect(await saving).toBe(true)
    expect(documents.get(tab.id)?.dirty).toBe(true)
    model(tab.id).undo()
    expect(documents.get(tab.id)?.dirty).toBe(false)
    model(tab.id).redo()
    expect(documents.get(tab.id)?.dirty).toBe(true)
  })
  it('keeps generated scripts dirty and preserves metadata when saving fails or is cancelled', async () => {
    const { documents, api, model } = documentFixture()
    const generated = documents.create('generated.sql', 'CREATE TABLE t(id int)', 'master', undefined, true)
    expect(documents.get(generated.id)?.dirty).toBe(true)
    api.saveSqlFile.mockResolvedValueOnce({ ok: true, value: null })
    expect(await documents.save(generated.id, true)).toBe(false)
    api.saveSqlFile.mockResolvedValueOnce({ ok: false, error: 'Disk full' })
    await expect(documents.save(generated.id)).rejects.toThrow('Disk full')
    expect(documents.get(generated.id)?.file).toBeUndefined()
    expect(documents.get(generated.id)?.dirty).toBe(true)
    model(generated.id).edit('')
    expect(documents.get(generated.id)?.dirty).toBe(false)
  })
  it('only disposes the closed model after session close succeeds, and detaches the last model', async () => {
    const { documents, api, model } = documentFixture()
    const left = documents.create('left.sql', '', 'master'), right = documents.create('right.sql', '', 'master')
    const instance = new TestEditor(); documents.bindEditor(instance.asEditor())
    api.closeQuerySession.mockResolvedValueOnce({ ok: false, error: 'Backend unavailable' })
    await expect(documents.close(right.id)).rejects.toThrow('Backend unavailable')
    expect(model(right.id).disposed).toBe(false)
    await documents.close(left.id)
    expect(api.closeQuerySession).toHaveBeenCalledWith(left.id)
    expect(model(left.id).disposed).toBe(true)
    expect(model(right.id).disposed).toBe(false)
    expect(instance.model).toBe(model(right.id))
    await documents.close(right.id)
    expect(instance.model).toBeNull()
    expect(documents.getSnapshot().activeId).toBe('')
  })
  it('does not discard changes made while session close is pending', async () => {
    const { documents, api, model } = documentFixture()
    const tab = documents.create('query.sql', 'SELECT 1', 'master')
    const pending = deferred<Awaited<ReturnType<typeof api.closeQuerySession>>>()
    api.closeQuerySession.mockReturnValueOnce(pending.promise)
    const closing = documents.runTask(() => documents.close(tab.id))
    expect(documents.getSnapshot().busy).toBe(true)
    model(tab.id).edit('SELECT 2')
    pending.resolve({ ok: true, value: { closed: true } })
    await expect(closing).rejects.toThrow('query changed while closing')
    expect(documents.getSnapshot().busy).toBe(false)
    expect(model(tab.id).disposed).toBe(false)
  })
  it('executes any nonempty selection with its source line and otherwise uses the whole model', () => {
    const { documents } = documentFixture()
    documents.create('query.sql', '-- heading\nSELECT 1;\nSELECT 2;', 'master')
    const instance = new TestEditor(); documents.bindEditor(instance.asEditor())
    instance.selection = { startLineNumber: 3, startColumn: 1, endLineNumber: 3, endColumn: 10, selectionStartLineNumber: 3, selectionStartColumn: 1, positionLineNumber: 3, positionColumn: 10 }
    expect(documents.getExecuteText()).toEqual({ sql: 'SELECT 2;', startLine: 3 })
    // A whitespace-only selection executes nothing rather than the whole document.
    instance.selection = { startLineNumber: 2, startColumn: 7, endLineNumber: 2, endColumn: 8, selectionStartLineNumber: 2, selectionStartColumn: 7, positionLineNumber: 2, positionColumn: 8 }
    expect(documents.getExecuteText()).toEqual({ sql: ' ', startLine: 2 })
    instance.selection = { startLineNumber: 2, startColumn: 7, endLineNumber: 2, endColumn: 7, selectionStartLineNumber: 2, selectionStartColumn: 7, positionLineNumber: 2, positionColumn: 7 }
    expect(documents.getExecuteText()).toEqual({ sql: '-- heading\nSELECT 1;\nSELECT 2;', startLine: 1 })
  })
  it('opens a value as a text document in its language, with no connection or session, saved with its kind', async () => {
    const { documents, api, model } = documentFixture()
    const query = documents.create('query.sql', 'SELECT 1', 'AppData', 'server-a')
    const xml = documents.openText({ name: 'doc1.xml', text: '<a/>', kind: 'xml' })
    expect(documents.get(xml.id)).toMatchObject({ name: 'doc1.xml', kind: 'xml', database: '', dirty: false })
    expect(documents.get(xml.id)?.connectionId).toBeUndefined()
    expect(documents.getSnapshot().activeId).toBe(xml.id)
    expect([model(xml.id).language, model(query.id).language]).toEqual(['xml', 'sql'])
    expect(model(documents.openText({ name: 'ExecutionPlan1.sqlplan', text: '<ShowPlanXML/>', kind: 'sqlplan' }).id).language).toBe('xml')
    expect(model(documents.openText({ name: 'data1.json', text: '{}', kind: 'json' }).id).language).toBe('json')
    // A new query from a value's tab gets master, not the value's empty database.
    documents.activate(xml.id)
    expect(documents.newQuery().database).toBe('master')
    await documents.save(xml.id)
    expect(api.saveSqlFile).toHaveBeenLastCalledWith({ fileId: undefined, name: 'doc1.xml', content: '<a/>', saveAs: false, kind: 'xml' })
    await documents.save(query.id)
    expect(api.saveSqlFile).toHaveBeenLastCalledWith({ fileId: undefined, name: 'query.sql', content: 'SELECT 1', saveAs: false })
    // Only a query has a SQL session to end.
    await documents.close(xml.id)
    expect(api.closeQuerySession).not.toHaveBeenCalled()
    expect(model(xml.id).disposed).toBe(true)
    await documents.close(query.id)
    expect(api.closeQuerySession).toHaveBeenCalledWith(query.id)
  })
  it('fills a large value a chunk a frame, never splitting a surrogate pair or a CRLF, and counts it saved after the last chunk', () => {
    const { documents, model, frames, frame } = documentFixture()
    const first = gridLimits.documentFirstChunk, chunk = gridLimits.documentChunk
    // The small first chunk opens the tab at once. It would end inside the emoji, and the next between CR and LF.
    const text = 'a'.repeat(first - 1) + '😀' + 'b'.repeat(chunk - 3) + '\r\n' + 'c'.repeat(2 * chunk + 10)
    const changes: boolean[] = []
    const value = documents.openText({ name: 'big.xml', text, kind: 'xml' })
    documents.subscribe(() => changes.push(documents.get(value.id)!.dirty))
    expect(model(value.id).getValueLength()).toBe(first - 1)
    expect(frames).toHaveLength(1)
    frame()
    expect(model(value.id).getValueLength()).toBe(first + chunk - 2)
    expect(model(value.id).getValue() === text.slice(0, first + chunk - 2)).toBe(true)
    frame()
    expect(model(value.id).getValueLength()).toBe(first + 2 * chunk - 2)
    expect(documents.get(value.id)?.dirty).toBe(false)
    while (frames.length) frame()
    expect(model(value.id).getValue() === text).toBe(true)
    expect(documents.get(value.id)).toMatchObject({ dirty: false, savedVersionId: model(value.id).getAlternativeVersionId() })
    expect(changes.every(dirty => !dirty)).toBe(true)
    model(value.id).edit(text + '!')
    expect(documents.get(value.id)?.dirty).toBe(true)
  })
  it('keeps a value dirty when it is typed in while it fills, and stops filling when it closes', async () => {
    const { documents, model, frames, frame } = documentFixture()
    const text = 'x'.repeat(3 * gridLimits.documentChunk)
    const typed = documents.openText({ name: 'typed.json', text, kind: 'json' })
    model(typed.id).edit('typed ' + model(typed.id).getValue())
    expect(documents.get(typed.id)?.dirty).toBe(false)
    while (frames.length) frame()
    expect(model(typed.id).getValueLength()).toBe(text.length + 6)
    expect(documents.get(typed.id)?.dirty).toBe(true)
    const closed = documents.openText({ name: 'closed.json', text, kind: 'json' })
    await documents.close(closed.id)
    frame()
    expect(frames).toHaveLength(0)
    expect(model(closed.id).getValueLength()).toBe(gridLimits.documentFirstChunk)
  })
  it('shows a large value without bracket matching or bracket colours, and turns matching back on for the others', () => {
    const { documents, model } = documentFixture()
    const query = documents.create('query.sql', 'SELECT (1)', 'master')
    const editor = new TestEditor()
    documents.bindEditor(editor.asEditor())
    const small = documents.openText({ name: 'small.json', text: '[' + '1,'.repeat(100) + '1]', kind: 'json' })
    const large = documents.openText({ name: 'large.xml', text: '<a>' + 'x'.repeat(gridLimits.documentBracketChars) + '</a>', kind: 'xml' })
    expect([model(query.id).options, model(small.id).options]).toEqual([{}, {}])
    expect(model(large.id).options).toEqual({ bracketColorizationOptions: { enabled: false, independentColorPoolPerBracketType: false } })
    // Matching is off before the large value is shown, and on again for the next document.
    expect(editor.options).toEqual([{ matchBrackets: 'never' }])
    expect(editor.model).toBe(model(large.id))
    documents.activate(small.id)
    documents.activate(query.id)
    expect(editor.options).toEqual([{ matchBrackets: 'never' }, { matchBrackets: 'always' }])
  })
  it('gives every model the indentation settings when it is created and whenever they change', () => {
    let indentation = { tabSize: 4, indentSize: 4, insertSpaces: false }
    const { documents, model } = documentFixture({ modelOptions: () => indentation })
    const first = documents.create('a.sql', '\tSELECT 1', 'master')
    const value = documents.openText({ name: 'v.json', text: '[1]', kind: 'json' })
    expect([model(first.id).options, model(value.id).options]).toEqual([indentation, indentation])
    indentation = { tabSize: 2, indentSize: 2, insertSpaces: true }
    documents.refreshOptions()
    expect([model(first.id).options, model(value.id).options]).toEqual([indentation, indentation])
  })
  it('matches brackets only while delimiter highlighting is on, and never in a large value', () => {
    let highlighting = false
    const { documents } = documentFixture({ matchBrackets: () => highlighting })
    const query = documents.create('query.sql', 'SELECT (1)', 'master')
    const editor = new TestEditor()
    documents.bindEditor(editor.asEditor())
    expect(editor.options).toEqual([{ matchBrackets: 'never' }])
    highlighting = true
    documents.refreshOptions()
    expect(editor.options.at(-1)).toEqual({ matchBrackets: 'always' })
    documents.openText({ name: 'large.xml', text: '<a>' + 'x'.repeat(gridLimits.documentBracketChars) + '</a>', kind: 'xml' })
    documents.refreshOptions()
    expect(editor.options.at(-1)).toEqual({ matchBrackets: 'never' })
    documents.activate(query.id)
    expect(editor.options.at(-1)).toEqual({ matchBrackets: 'always' })
  })
})

describe('custom documents', () => {
  function withProvider() {
    const fixture = documentFixture()
    const provider = { kind: 'tableDesigner' as const, inSaveAll: true, save: async () => true, canClose: () => undefined, revision: () => 7, focus: (id: string) => { focused.push(id) }, closed: (id: string) => { closed.push(id) }, follows: () => false }
    const focused: string[] = [], closed: string[] = []
    fixture.documents.registerProvider(provider)
    return { ...fixture, provider, focused, closed }
  }
  it('opens a designer with no model: the editor shows nothing while it is active, and the query again after', async () => {
    const { documents, model, focused, closed, api } = withProvider()
    const query = documents.create('query.sql', 'SELECT 1', 'master')
    const instance = new TestEditor()
    documents.bindEditor(instance.asEditor())
    const tab = documents.openCustom('tableDesigner', 'srv.db - dbo.Table_1', 'server-a', 'db')
    expect(documents.active).toMatchObject({ id: tab.id, kind: 'tableDesigner', dirty: false, connectionId: 'server-a', database: 'db' })
    expect(documents.isCustom(tab.id) && !documents.isCustom(query.id)).toBe(true)
    expect(instance.model).toBeNull()
    expect(documents.getModel(tab.id)).toBeUndefined()
    expect(documents.revision(tab.id)).toBe(7)
    expect(documents.revision(query.id)).toBe(model(query.id).getVersionId())
    documents.focusActive()
    expect(focused).toEqual([tab.id])
    documents.setDirty(tab.id, true)
    expect(documents.get(tab.id)?.dirty).toBe(true)
    documents.activate(query.id)
    expect(instance.model).toBe(model(query.id))
    await documents.close(tab.id)
    expect(closed).toEqual([tab.id])
    expect(documents.get(tab.id)).toBeUndefined()
    expect(api.closeQuerySession).not.toHaveBeenCalled()
  })
  it('needs a provider for the kind, and one provider per kind', () => {
    const { documents, provider } = withProvider()
    expect(() => documents.registerProvider(provider)).toThrow('already registered')
    const bare = documentFixture()
    expect(() => bare.documents.openCustom('tableDesigner', 'x', undefined, 'db')).toThrow('No tableDesigner provider')
  })
})

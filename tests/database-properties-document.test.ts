    expect(await again).toBe(false)
    expect(properties.canEdit(id)).toBe(false)
    expect(properties.canApply(id)).toBe(false)
    expect(properties.canRefresh(id)).toBe(false)
    properties.discard(id)
    expect(properties.canRefresh(id)).toBe(false)

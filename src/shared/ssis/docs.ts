// Renders the generated part of docs/integration-services.md from the catalogue: everything after `generatedMarker`.
// tests/ssis-catalog.test.ts keeps the file in sync and leaves the hand-written part above the marker as it is.
import {
  catalogDatabase, describeTargets, describeViews, executableResults, loggingLevels, messageSourceTypes, messageTypes, operationStatuses, operationTypes, openStatuses,
  parameterObjectTypes, permissionTypes, referenceTypes, securableTypes, ssisErrorCodes, ssisErrorRetryable, ssisFeatureSources, ssisFeatures, ssisLimits, systemParameters,
  valueTypes, finalStatuses, ssisActions, ssisActionVerbs, stoppableOperationTypes, createCatalog, type CodeLabel, type SsisActionSpec
} from './catalog.ts'
import { folderSpecs, kindSpecs } from '../explorer/catalog.ts'
import { createCatalogDrainMs } from '../ipc/methods.ts'

export const generatedMarker = '<!-- Generated below from src/shared/ssis/catalog.ts. Regenerate with: npx vitest run tests/ssis-catalog.test.ts -u -->'

const cell = (value: string) => value.replaceAll('|', '\\|')
const row = (cells: readonly string[]) => '| ' + cells.map(cell).join(' | ') + ' |'
const table = (header: readonly string[], rows: readonly (readonly string[])[]) => [row(header), row(header.map(() => '---')), ...rows.map(row)].join('\n')
const code = (value: string | number) => '`' + value + '`'
const codes = (rows: readonly CodeLabel[]) => table(['Code', 'Meaning'], rows.map(item => [code(item.code), item.label]))
const versions: Readonly<Record<number, string>> = { 13: '2016', 14: '2017', 15: '2019', 16: '2022', 17: '2025' }

const limitNotes: Readonly<Record<keyof typeof ssisLimits, string>> = {
  name: 'UTF-16 code units in a folder, project, environment, parameter or variable name (sysname)',
  packageName: 'UTF-16 code units in a package name (`catalog.packages.name` is nvarchar(260))',
  description: 'Characters in a description',
  value: 'Characters of a parameter, variable or catalog property value; a longer one ends in "…"',
  rows: 'Rows one describe list holds (packages, parameters, references, variables, properties); more set `truncated`',
  describeBytes: 'Estimated bytes of one describe answer; rows past it set `truncated`',
  revision: 'Characters in a revision (a SHA-256 in hex)',
  messageChars: 'Characters in an error message',
  describeMs: 'A describe\'s budget, in ms, answered as `TIMEOUT`',
  gateWaitMs: 'How long a request waits for an SSIS read or write gate before `BUSY`, in ms',
  readPerConnection: 'SSIS reads at once per connection',
  readTotal: 'SSIS reads at once in all',
  registered: 'SSIS requests registered at once',
  cancelIds: 'Request ids per `varia:ssis-cancel`',
  tombstones: 'Ids main remembers that were cancelled before they were sent',
  tombstoneMs: 'How long main remembers them, in ms',
  readLockTimeoutMs: 'LOCK_TIMEOUT of the tree\'s and describe\'s reads, in ms',
  profileLockTimeoutMs: 'LOCK_TIMEOUT of the profile read (its role checks), in ms',
  writePerConnection: 'SSIS writes (`ssis.execute`) at once per connection',
  writeTotal: 'SSIS writes at once in all',
  registeredWrites: 'SSIS writes registered at once',
  preflightLockTimeoutMs: 'LOCK_TIMEOUT of a write\'s preflight, in ms (`BLOCKED`)',
  preflightMs: 'A write\'s preflight budget, in ms, answered as `TIMEOUT`',
  stopGraceMs: 'How long a stopped write\'s reply waits for SQL Server to end its statement, in ms, then answers `CANCELLED` (outcome unknown)',
  createDrainMs: 'How long a backend that is shutting down waits for a Create Catalog past its restore to finish, or to remove what it created, in ms',
  catalogPassword: 'UTF-16 code units in Create Catalog\'s encryption password (at least 1; the server\'s password policy applies too)',
  serverPath: 'Characters in a path Create Catalog reads on the server (the catalog backup, the assembly, the database files)'
}

const viewNotes: Readonly<Record<typeof describeViews[number], string>> = {
  catalog: 'The connection\'s profile (band, engine, host platform, authentication, RCSI, features, roles), the folders the login may read, and `catalog_properties` for ssis_admin and sysadmin',
  folder: 'Id, name, description, creator, created time, and its project and environment counts',
  project: 'Its row (deployment, version LSN, validation), its packages, its parameters (object type 20) and its environment references',
  package: 'Its row (format, version, entry point, validation) and its parameters (object type 30)',
  environment: 'Its row and its variables; a sensitive variable\'s value is never read'
}

export function renderSsisDocs(): string {
  const tree = (['integrationServicesCatalogs', 'ssisProjects', 'ssisEnvironments', 'ssisPackages'] as const).map(id => folderSpecs[id])
  return [
    generatedMarker,
    '',
    '## Catalogue reference',
    '',
    'Everything below comes from `src/shared/ssis/catalog.ts`, which the backend embeds as `backend/Varia.Backend/Ssis/ssis-catalog.json`.',
    `The catalog is the database ${code(catalogDatabase)} (SSMS fixes the name; only an internal test option points the backend at a fake catalog).`,
    '',
    '### The tree',
    '',
    'Object Explorer serves the catalog as SSMS does, from SQL Server 2016: the server\'s Integration Services Catalogs folder lists the',
    'catalog\'s database when it exists, the catalog lists its folders directly, a folder has Projects and Environments, and a project',
    'has Packages. Packages list in deployment order (`package_id`), because a package name can be longer than a sysname cursor key; a',
    'package that is not an entry point has the subtype `child`. On SQL Server on Linux the folder says the catalog is not supported. The',
    'kinds, folders and their identity are in docs/object-explorer.md.',
    '',
    table(['Folder', 'Id', 'Lists (query)', 'Filters'], tree.map(spec => [spec.label, code(spec.id), `${(spec.rows ?? []).map(kind => kindSpecs[kind].title).join(', ')} (${code(spec.list!)})`,
      spec.filter?.length ? 'Name' : '—'])),
    '',
    'The catalog\'s listings run on the SSIS read pool (the program name plus " - Integration Services"), whose connections are in the',
    'catalog\'s database, at READ UNCOMMITTED with `LOCK_TIMEOUT 5000`. The catalog row itself is read from `sys.databases` on the Object',
    'Explorer pool. A catalog that was dropped answers `NOT_FOUND` (refresh the parent); one that is offline, restoring or single-user in',
    'use, `DATABASE_UNAVAILABLE` (retry); one the login cannot open, `NO_DB_ACCESS`.',
    '',
    '### Reads (`ssis.describe`)',
    '',
    'One request reads one view in one batch, under the SSIS gates, and answers its model with a `revision`, or an error value. The',
    'revision is a SHA-256 of what a later write depends on (names, descriptions, a project\'s deployment, parameter values,',
    'references, variables, catalog properties), not of validation results or counts, which change without a write; a truncated answer',
    'has none.',
    'Reads run READ COMMITTED when the catalog\'s database has READ_COMMITTED_SNAPSHOT on, otherwise READ UNCOMMITTED, with',
    `\`LOCK_TIMEOUT ${ssisLimits.readLockTimeoutMs}\`; a read that meets the catalog's cleanup moving rows (error 601) reads once more. The first read on a`,
    'connection also reads its profile, with the role checks at the live reads\' `LOCK_TIMEOUT 1000`, because `IS_MEMBER` waits on a pending',
    'change to a role\'s members; a sysadmin\'s are not evaluated.',
    '',
    table(['View', 'Describes', 'Model'], describeViews.map(view => [code(view), code(describeTargets[view]), viewNotes[view]])),
    '',
    table(['Feature', 'Found when the catalog has'], ssisFeatures.map(feature => [code(feature), code(ssisFeatureSources[feature])])),
    '',
    table(['Error', 'Retry helps'], ssisErrorCodes.map(item => [code(item), ssisErrorRetryable[item] ? 'Yes' : 'No'])),
    '',
    '### Writes (`ssis.execute`)',
    '',
    'A write runs on a connection of its own, opened for the request and closed after it: unpooled, never retried, in the catalog\'s',
    'database (Create Catalog\'s in `master`), under the program name plus " - Integration Services Actions", so DBAs can tell it from the',
    `read pool. It takes the SSIS write gates (${ssisLimits.writePerConnection} per connection, ${ssisLimits.writeTotal} in all), then runs a preflight in the same connection at READ`,
    `COMMITTED with \`LOCK_TIMEOUT ${ssisLimits.preflightLockTimeoutMs}\` (within ${ssisLimits.preflightMs / 1000} s), then its steps in order, from \`SsisSql\`'s constant templates (Create`,
    'Catalog\'s from `SsisCreateSql`) with values as parameters, waiting for locks as SSMS does (`LOCK_TIMEOUT -1`), with no outer transaction.',
    `Stop (\`varia:ssis-cancel\`) ends it at any time (Create Catalog at any statement but its restore): the reply waits up to ${ssisLimits.stopGraceMs / 1000} s for SQL Server to`,
    'end the statement and lists the steps that completed (done, failed, cancelled, skipped). On a box server SSISDB changes nothing for a SQL Server login (error 27123), so a verb that needs',
    'Windows authentication answers `WINDOWS_AUTH_REQUIRED` before it connects. Nothing is logged: not names, values, SQL or messages.',
    '',
    table(['Verb', 'Title', 'Runs in', 'Steps', 'Calls', 'Takes a revision', 'On a box server'], ssisActionVerbs.map(verb => {
      const spec: SsisActionSpec = ssisActions[verb]
      return [code(verb), spec.title, spec.scope === 'catalog' ? 'The catalog\'s database' : code('master'), spec.steps.join('; '),
        spec.procedures.length ? spec.procedures.map(name => code('catalog.' + name)).join(', ') : '—', spec.revision ? 'Yes' : 'No',
        spec.windowsAuthOnBox ? 'Windows authentication only' : 'Any authentication']
    })),
    '',
    'Stop Operation\'s preflight reads the operation from `catalog.operations`: one this login cannot see, or that no longer exists,',
    `answers \`NOT_FOUND\`; one that is not an execution or validation (types ${stoppableOperationTypes.map(code).join(', ')}), \`NOT_SUPPORTED\`; one that has`,
    'ended or is already stopping, `ALREADY_FINAL`; an execution that was created and never started (it never runs), `NOT_STARTED`. Otherwise',
    'it calls `catalog.stop_operation`, which records a stop operation (type 202) of its own and makes the operation Stopping (8) until',
    'the package ends (Canceled, 3). When the catalog refuses because the operation is not running (27124) or already stopping (27126),',
    'the operation is read again: `ALREADY_FINAL` if it ended or is stopping, `NOT_RUNNING` (retry once it runs) if it is pending, and',
    'the catalog\'s own refusal if that second look fails. A lost connection before the stop is sent says nothing changed; after, that',
    'its outcome is unknown. The catalog records its stop operation as Running before its own transaction, and a cancelled statement',
    'never reaches its error path, so Stop during `catalog.stop_operation` (waiting on a lock) rolls the stop back but may leave that',
    'Stop operation Running until SQL Server restarts and the catalog\'s startup procedure ends it; the `CANCELLED` reply says so.',
    '',
    '#### Create Catalog',
    '',
    'Create Catalog does what SSMS 22\'s `Catalog.Create` does (read from its object model), on a write connection of its own in `master`.',
    'Its dialog first reads `ssis.catalogSetup` on the SSIS read pool, and the write reads the same again before its first step:',
    'sysadmin, whether the catalog\'s database exists, `clr enabled` in use and `scan for startup procs` (SSMS\'s default for the startup',
    'procedure), the Integration Services folder from the registry value',
    '`HKLM\\SOFTWARE\\Microsoft\\Microsoft SQL Server\\<major>0\\SSIS\\Setup\\DTSPath` (`xp_regread` on the server, as SSMS reads it),',
    `the catalog backup in its \`Binn\` folder (${createCatalog.backupFiles.map(item => `${code(item.file)} from ${versions[item.since]}`).join(', ')}: the one name SSMS 22's \`Catalog.Create\` passes for every version) and ${code(createCatalog.assemblyFile)}`,
    'beside it, whether the backup exists (`xp_fileexist`), the database files\' folder (the master database\'s, from `SERVERPROPERTY(\'MasterFile\')`,',
    'where SSMS puts them) and that `SSISDB.mdf` and `SSISDB.ldf` are not there yet, and the backup\'s logical files (`RESTORE FILELISTONLY`).',
    'It is refused before it connects on SQL Server before 2016, on Linux, and on Azure SQL Database and Managed Instance (an Azure-SSIS',
    'integration runtime creates that catalog); then without sysadmin (`PERMISSION_DENIED`), when the catalog exists (`CATALOG_EXISTS`),',
    'when the backup or the folders cannot be found or the files exist (`NOT_SUPPORTED`, in SSMS\'s words), and when CLR integration is',
    'off and the request did not agree to enable it (`CLR_REQUIRED`), or when CLR integration is off and other dynamic `sp_configure` changes',
    'wait for a `RECONFIGURE` (`CONFIGURATION_PENDING`, naming them; `min server memory (MB)` at 0 never counts, because SQL Server always',
    'shows it in use as 16): the user agreed to CLR integration, not to them. Then, in order:',
    '',
    '1. **Enable CLR integration** (only when it is off): `sp_configure \'clr enabled\', 1` and `RECONFIGURE`, as SMO does for SSMS\'s dialog.',
    '2. **Restore the catalog database**: `RESTORE DATABASE` with the name, the backup, the logical names and the new files as parameters,',
    '   refused (27135) if the database appeared meanwhile, then `SET READ_WRITE` if it restored read-only. Unlike SSMS it does not use',
    '   `WITH REPLACE`, so nothing that appeared meanwhile is overwritten.',
    '3. **Create the master key**: SSMS\'s statement, after dropping a master key the backup might hold, with the password a parameter',
    '   that the server quotes (`REPLACE` of each quote inside `EXEC`). Unlike SSMS the literal is an `N` literal, so a password with',
    '   characters outside the server\'s code page keeps them, and the `REPLACE` compares in `Latin1_General_BIN2`: in a width-insensitive',
    '   collation it would double U+FF07 (fullwidth apostrophe), which the literal reads as an ASCII quote, so the key\'s password would',
    '   not be the one typed. The assembly\'s path and the cleanup login\'s random password are quoted the same way.',
    '4. **Register the Integration Services assembly and startup procedure**: after 14.0.800.11 (SQL Server 2017 and later, as SSMS',
    '   decides it) the assembly\'s SHA2_512 hash with `sys.sp_add_trusted_assembly`, read (and kept for the removal) in one statement',
    '   before another adds it, so an add that Stop or a lost reply cuts short is still removed; before, the asymmetric key',
    '   `MS_SQLEnableSystemAssemblyLoadingKey`, its login and `UNSAFE ASSEMBLY`. Then `master.dbo.sp_ssis_startup` (SSMS\'s text), and',
    '   `sp_procoption` when the startup procedure was chosen.',
    '5. **Create the maintenance job**: `##MS_SSISServerCleanupJobLogin##` with a random password the server generates, disabled, its user',
    '   in the catalog with EXECUTE on the two cleanup procedures, `VIEW SERVER STATE`, and the `SSIS Server Maintenance Job` (two T-SQL',
    '   steps, daily at 00:00), as SSMS\'s CreateCleanupJobLogin.sql and CreateMaintenanceJob.sql do. Like SSMS it creates no',
    '   `SSIS Failover Monitor Job`: that belongs to Always On support.',
    '',
    `When a step after the restore fails or is stopped, Create Catalog does what SSMS does after a failure and adds the step "${createCatalog.cleanupStep}":`,
    'it ends a transaction the cancelled statement left open, then drops what this request made: the trusted assembly hash it added,',
    '`sp_ssis_startup`, both SSIS jobs and the cleanup login, and then the database it restored, so the server is as before (CLR stays',
    'enabled, as in SSMS). Its statements wait at most 30 s for a lock, because nothing can stop them. A refused restore (the database',
    'appeared meanwhile) removes nothing, and a database left restoring by a failed restore is dropped only while no other session holds a',
    'lock on it (another restore of the same name holds an exclusive one). Stop ends Create Catalog at any statement but the restore',
    'itself (and its switch to read-write), because a half-restored catalog is worse than waiting: Stop during the restore lets it end,',
    'then removes what it created; Stop at a later statement, waiting for a lock or not, has SQL Server cancel it and removes what was',
    'created. Its reply waits for that, past the usual grace, a disconnect included, and lists the steps (the removal\'s own failures',
    `clipped to ${ssisLimits.messageChars.toLocaleString('en-US')} characters). A backend that shuts down (a quit, a closed window, a renderer reload, Restart Backend) waits up to`,
    `${ssisLimits.createDrainMs / 1000} s for a Create Catalog past its restore to finish or remove what it made, and main lets that generation run ${createCatalogDrainMs / 1000} s after its`,
    'stdin ends (2 s otherwise) before it kills it; only a kill or a crash in that window leaves an incomplete catalog, which Create Catalog then',
    'refuses as `CATALOG_EXISTS` until its database is dropped. The CLR agreement is checked from the server\'s facts before any step, in a',
    'dry run too. The password is a parameter only, well-formed UTF-16 (a lone surrogate would reach the server as U+FFFD): it is never in',
    'SQL text Varia builds, in messages, in logs or on disk, and the request\'s frame is zeroed on both sides.',
    '',

    '### Code tables',
    '',
    `Operation types (\`catalog.operations.operation_type\`):`,
    '',
    codes(operationTypes),
    '',
    `Operation statuses; open: ${openStatuses.map(code).join(', ')}, final: ${finalStatuses.map(code).join(', ')}:`,
    '',
    codes(operationStatuses),
    '',
    'Message types, with the tone a log row takes:',
    '',
    table(['Code', 'Meaning', 'Tone'], messageTypes.map(item => [code(item.code), item.label, item.tone])),
    '',
    'Message source types:',
    '',
    codes(messageSourceTypes),
    '',
    'Executable results:',
    '',
    codes(executableResults),
    '',
    'Logging levels:',
    '',
    table(['Code', 'Meaning', 'Since'], loggingLevels.map(item => [code(item.code), item.label, item.since ? `${versions[item.since]} (${item.since})` : '—'])),
    '',
    'Parameter object types:',
    '',
    codes(parameterObjectTypes),
    '',
    `System parameters an execution may set: ${systemParameters.map(code).join(', ')}. \`SYNCHRONIZED\` is absent by design.`,
    '',
    'Securable types and permissions:',
    '',
    codes(securableTypes),
    '',
    table(['Code', 'Permission', 'On'], permissionTypes.map(item => [code(item.code), item.label, item.on.map(on => securableTypes.find(type => type.code === on)!.label).join(', ')])),
    '',
    `Environment reference types: ${referenceTypes.map(item => `${code(item.code)} ${item.label}`).join(', ')}. Parameter value types: ${valueTypes.map(item => `${code(item.code)} ${item.label}`).join(', ')}.`,
    '',
    '### Limits',
    '',
    table(['Limit', 'Value', 'Meaning'], (Object.keys(limitNotes) as (keyof typeof ssisLimits)[]).map(key => [code(key), ssisLimits[key].toLocaleString('en-US'), limitNotes[key]])),
    ''
  ].join('\n')
}

let keys: Map<number, number> | undefined
/** The code point OrdinalIgnoreCase compares `code` as. */
export function ordinalKey(code: number): number {
  if (!keys) {
    keys = new Map()
    for (const [first, last, delta, stride] of ranges) for (let at = first; at <= last; at += stride) keys.set(at, at + delta)
  }
  return keys.get(code) ?? code
}

/** String.Equals(a, b, StringComparison.OrdinalIgnoreCase): the same length, and each code point equal or of the same key
 *  (a lone surrogate is a code point of its own). */
export function sameName(a: string, b: string): boolean {
  if (a.length !== b.length) return false
  for (let at = 0; at < a.length;) {
    const x = a.codePointAt(at)!, y = b.codePointAt(at)!
    const size = x > 0xffff ? 2 : 1
    if (size !== (y > 0xffff ? 2 : 1)) return false
    if (x !== y && ordinalKey(x) !== ordinalKey(y)) return false
    at += size
  }
  return true
}

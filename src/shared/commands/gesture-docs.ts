import { commandDescriptor } from './catalog'
import { gestureDefault, gestureDescriptor, gestureIds, gestureLabel, gestureOptions, gestureScopes, modifiersLabel, type GestureKind } from './gestures'
import { platforms, type Platform } from './keybindings'

const platformNames: Readonly<Record<Platform, string>> = { win32: 'Windows', linux: 'Linux', darwin: 'macOS' }
const kindNames: Readonly<Record<GestureKind, string>> = { modifier: 'Modifier', pointerCommand: 'Command', fixed: 'Fixed' }
const cell = (text: string) => text.replaceAll('|', '\\|')
const row = (cells: readonly string[]) => `| ${cells.map(cell).join(' | ')} |`

/** docs/gestures.md: every mouse gesture with its default on each platform, whether it can be remapped, and its keyboard path. */
export function renderGestureDocs(): string {
  const lines = [
    '# Varia mouse gestures',
    '',
    '<!-- Generated by renderGestureDocs() in src/shared/commands/gesture-docs.ts. Update with: npx vitest run tests/gestures.test.ts -u -->',
    '',
    'Every pointer gesture that reads a modifier, runs a command, or is fixed by the platform is declared in',
    '`src/shared/commands/gestures.ts`. Handlers ask `GestureService` (`src/renderer/src/core/gestures.ts`) whether an event',
    'matches; a gesture matches when all of its modifiers are held. "Modifier" gestures switch a behaviour on while',
    'pointing; "Command" gestures run a command that the keyboard also reaches; "Fixed" gestures belong to the platform,',
    'Chromium, or a library and cannot be remapped. "Choices" are the modifiers the Shortcuts page will offer.',
    '',
    `## Gestures (${gestureIds.length})`
  ]
  for (const scope of Object.keys(gestureScopes) as (keyof typeof gestureScopes)[]) {
    const ids = gestureIds.filter(id => gestureDescriptor(id).scope === scope)
    if (!ids.length) continue
    lines.push('', `### ${gestureScopes[scope]}`, '', row(['Gesture', 'Id', 'What it does', 'Kind', ...platforms.map(platform => platformNames[platform]), 'Choices or lock', 'Keyboard']),
      row(['---', '---', '---', '---', ...platforms.map(() => '---'), '---', '---']))
    for (const id of ids) {
      const gesture = gestureDescriptor(id)
      const on = (platform: Platform) => gesture.platforms && !gesture.platforms.includes(platform) ? '—' : `${gestureLabel(gesture.action, gestureDefault(id, platform), platform)} ${gesture.target}`
      // The nth choice on each platform (macOS may offer its own, in the same order), then Off where allowed.
      const choices = gesture.choices ? 'Choose: ' + gestureOptions(id, 'win32').map((_, index) => platforms.map(platform => {
        const choice = gestureOptions(id, platform)[index]
        return choice === null ? 'Off' : modifiersLabel(choice, platform)
      }).filter((label, at, all) => all.indexOf(label) === at).join(' / ')).join(', ') : `Locked: ${gesture.locked}`
      const keyboard = gesture.keyboard?.map(command => commandDescriptor(command).title + ` (\`${command}\`)`).join(', ') ?? '—'
      const title = gesture.title + (gesture.alsoIn ? ` (also ${gesture.alsoIn.map(other => gestureScopes[other]).join(', ')})` : '')
      lines.push(row([title, `\`${id}\``, gesture.description, kindNames[gesture.kind], ...platforms.map(on), choices, keyboard]))
    }
  }
  return lines.join('\n') + '\n'
}

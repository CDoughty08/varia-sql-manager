import { planCanvas, planViewer, documentTabs, floatingEditorGroups } from './ui.mjs'
import { resizeContent } from './window-resize.mjs'
import { resolve } from 'node:path'

/** The diagnostics saved plan is open. Drive the same toolbar, outline and document menus people use. */
export async function checkCanvasUx({ application, page, expect }) {
  const viewer = planViewer(page), canvas = planCanvas(page)
  const button = name => viewer.getByRole('button', { name, exact: true })
  const selected = () => viewer.getByRole('treeitem', { selected: true })
  const outlineSize = () => viewer.getByRole('separator', { name: 'Resize plan outline', exact: true })
  const propertiesSize = () => viewer.getByRole('separator', { name: 'Resize plan properties', exact: true })
  await viewer.getByRole('combobox', { name: 'Operator ranking' }).selectOption('plan')
  await viewer.getByRole('treeitem').filter({ hasText: 'Sort' }).click()
  await button('Reset plan zoom to 100%').click()
  const zoom = await button('Reset plan zoom to 100%').innerText()
  await outlineSize().focus(); await page.keyboard.press('ArrowRight')
  await expect(outlineSize()).toHaveAttribute('aria-valuenow', '236')
  const splitter = await outlineSize().boundingBox()
  await page.mouse.move(splitter.x + splitter.width / 2, splitter.y + 40); await page.mouse.down()
  await page.mouse.move(splitter.x + splitter.width / 2 + 24, splitter.y + 40); await page.mouse.up()
  await expect(outlineSize()).toHaveAttribute('aria-valuenow', '260')
  const moved = await outlineSize().boundingBox()
  await page.mouse.move(moved.x + moved.width / 2, moved.y + 40); await page.mouse.down()
  await page.mouse.move(moved.x + moved.width / 2 - 24, moved.y + 40); await page.mouse.up()
  await expect(outlineSize()).toHaveAttribute('aria-valuenow', '236')
  await propertiesSize().focus(); await page.keyboard.press('ArrowRight')
  await expect(propertiesSize()).toHaveAttribute('aria-valuenow', '244')
  await button('Collapse inputs').click()
  await expect(selected()).toHaveAttribute('aria-expanded', 'false')
  await button('Go to XML').click()
  await expect(page.getByRole('button', { name: 'XML source', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('code')).toContainText('RelOp NodeId="0"')
  await page.getByRole('button', { name: 'Graph', exact: true }).click()
  await expect(selected()).toContainText('Sort')
  await expect(selected()).toHaveAttribute('aria-expanded', 'false')
  await expect(button('Reset plan zoom to 100%')).toHaveText(zoom)
  await expect(outlineSize()).toHaveAttribute('aria-valuenow', '236')
  await viewer.getByRole('searchbox', { name: 'Find plan operators' }).fill('Index Seek')
  await viewer.getByRole('treeitem').click()
  await expect(selected()).toContainText('Index Seek')
  await viewer.getByRole('searchbox', { name: 'Find plan operators' }).fill('')
  await expect(viewer.getByRole('treeitem').filter({ hasText: 'Sort' })).toHaveAttribute('aria-expanded', 'true')
  // XML still has Sort's caret from Go to XML. A view-only round trip must keep Index Seek selected.
  await page.getByRole('button', { name: 'XML source', exact: true }).click()
  await page.getByRole('button', { name: 'Graph', exact: true }).click()
  await expect(selected()).toContainText('Index Seek')
  await button('Statement SQL').click()
  await expect(viewer.getByRole('region', { name: 'Statement SQL from plan' })).toContainText('SELECT Amount FROM dbo.Orders')
  await button('Back to graph').click()
  await expect(canvas.locator('canvas')).toHaveCount(1)
  await expect(selected()).toContainText('Index Seek')
  const minimap = button('Plan minimap')
  await minimap.focus(); await page.keyboard.press('ArrowRight'); await page.keyboard.press('Home')
  await minimap.click({ position: { x: 80, y: 48 } })
  await button('Row flow').click()
  await expect(button('Row flow')).toHaveAttribute('aria-pressed', 'false')
  // The flat virtual outline remains the complete screen reader alternative, including row-flow provenance.
  const aria = await viewer.getByRole('tree', { name: 'Plan operators' }).ariaSnapshot()
  expect(aria).toMatch(/tree "Plan operators"/)
  expect(aria).toMatch(/treeitem.*Sort.*Actual 100 rows/)
  expect(aria).toMatch(/treeitem.*Index Seek.*Actual 10 rows/)
  await page.emulateMedia({ forcedColors: 'active' })
  await expect(canvas).toBeHidden()
  await expect(viewer.getByRole('treeitem').first()).toBeVisible()
  await viewer.getByRole('tree', { name: 'Plan operators' }).focus(); await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight')
  await expect(selected()).toContainText('Index Seek')
  await button('Statement SQL').click()
  await expect(viewer.getByRole('region', { name: 'Statement SQL from plan' })).toBeVisible()
  await button('Back to graph').click()
  await expect(viewer.getByRole('tree', { name: 'Plan operators' })).toBeFocused()
  await page.emulateMedia({ forcedColors: 'none' })
  await expect(canvas.locator('canvas')).toHaveCount(1)
  await resizeContent(application, page, 760, 600)
  await expect(viewer.getByRole('treeitem').first()).toBeInViewport()
  await button('Outline').click(); await button('Properties').click()
  await expect(canvas).toBeVisible()
  await button('Outline').click(); await button('Properties').click()
  await resizeContent(application, page, 1200, 850)
  const tab = documentTabs(page).getByRole('tab', { name: 'diagnostics.sqlplan', exact: true })
  await tab.click({ button: 'right' }); await page.getByRole('menu', { name: 'Query tab', exact: true }).getByRole('menuitem', { name: 'Split Right', exact: true }).click()
  await expect(canvas.locator('canvas')).toHaveCount(1)
  await tab.click({ button: 'right' }); await page.getByRole('menu', { name: 'Query tab', exact: true }).getByRole('menuitem', { name: 'Float', exact: true }).click()
  await expect(floatingEditorGroups(page)).toHaveCount(1)
  await expect(selected()).toContainText('Index Seek')
  await expect(outlineSize()).toHaveAttribute('aria-valuenow', '236')
  await tab.click({ button: 'right' }); await page.getByRole('menu', { name: 'Query tab', exact: true }).getByRole('menuitem', { name: 'Dock', exact: true }).click()
  await expect(floatingEditorGroups(page)).toHaveCount(0)
  // Restore defaults for the caller and other assertions in the same isolated launch.
  await outlineSize().focus(); await page.keyboard.press('ArrowLeft')
  await propertiesSize().focus(); await page.keyboard.press('ArrowLeft')
  await button('Row flow').click()
  await button('Outline').click(); await button('Properties').click(); await button('Fit batch').click()
  await page.screenshot({ path: resolve('artifacts/plan-canvas-ux.png') })
  await button('Outline').click(); await button('Properties').click()
  console.log('Canvas UX: collapse/search reveal, XML targeting, SQL, minimap keyboard/pointer, persisted splitters, ARIA, forced colors, small window, split and floating document.')
}
